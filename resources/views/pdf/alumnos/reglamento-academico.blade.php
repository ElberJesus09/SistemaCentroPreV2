        <tr>
            <td class="article-number">Art. 56</td>
            <td class="article-content">
                <span class="article-title">Faltas leves</span><br>
                Son faltas leves las siguientes conductas:
                <ol class="alpha" type="a">
                    <li>Llegar tarde a clases o a cualquier actividad acad&eacute;mica obligatoria hasta en tres (3) ocasiones durante el ciclo, sin justificaci&oacute;n v&aacute;lida.</li>
                    <li>No portar el carn&eacute; de identificaci&oacute;n del CPU cuando sea requerido por autoridad competente.</li>
                    <li>Usar tel&eacute;fonos celulares, dispositivos electr&oacute;nicos o cualquier otro objeto que perturbe el normal desarrollo de las clases, sin autorizaci&oacute;n del docente.</li>
                    <li>Consumir alimentos o bebidas dentro de las aulas o durante el desarrollo de actividades acad&eacute;micas, salvo autorizaci&oacute;n expresa.</li>
                    <li>No mantener el orden y limpieza en las instalaciones del CPU.</li>
                    <li>Realizar ruidos o conductas que perturben el desarrollo de las clases, siempre que no constituyan falta grave.</li>
                    <li>Incurrir en cualquier otra conducta que, por su escasa significaci&oacute;n, afecte levemente el normal funcionamiento del CPU.</li>
                </ol>
            </td>
        </tr>
    </table>

    <table class="article">
        <tr>
            <td class="article-number">Art. 57</td>
            <td class="article-content">
                <span class="article-title">Faltas graves</span><br>
                Son faltas graves las siguientes conductas:
                <ol class="alpha" type="a">
                    <li>Reincidir en tres (3) o m&aacute;s faltas leves durante el mismo ciclo acad&eacute;mico, despu&eacute;s de haber sido amonestado por escrito.</li>
                    <li>Faltar injustificadamente a clases por m&aacute;s del 10% de las horas lectivas del ciclo, sin perjuicio de lo establecido en el r&eacute;gimen acad&eacute;mico.</li>
                    <li>Sustraer, retener o utilizar sin autorizaci&oacute;n materiales, equipos o bienes del CPU.</li>
                    <li>Alterar, falsificar o usar indebidamente documentos, firmas, calificaciones o carn&eacute;s.</li>
                    <li>Incurrir en actos de desobediencia o resistencia a las indicaciones del personal docente o administrativo en el ejercicio de sus funciones.</li>
                    <li>Realizar actividades comerciales o lucrativas no autorizadas dentro de las instalaciones del CPU.</li>
                    <li>Ingresar a zonas restringidas sin autorizaci&oacute;n.</li>
                    <li>Realizar actos de acoso escolar (bullying) o cualquier forma de maltrato psicol&oacute;gico entre estudiantes.</li>
                </ol>
            </td>
        </tr>
    </table>


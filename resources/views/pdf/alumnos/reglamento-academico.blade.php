            <td class="article-content"><span class="article-title">Reincidencia</span><br>Se considera reincidente al estudiante que, dentro de un mismo ciclo acad&eacute;mico o en el ciclo inmediato posterior, incurra en una nueva falta de la misma naturaleza o mayor gravedad, despu&eacute;s de haber sido sancionado por falta anterior. La reincidencia ser&aacute; considerada como agravante al momento de determinar la sanci&oacute;n, pudiendo dar lugar a la aplicaci&oacute;n de una sanci&oacute;n m&aacute;s grave, inclusive la separaci&oacute;n definitiva en caso de reiteraci&oacute;n de faltas graves.</td>
        </tr>
    </table>

    <table class="article">

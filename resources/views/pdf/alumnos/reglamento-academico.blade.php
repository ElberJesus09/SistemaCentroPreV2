        <tr>
            <td class="article-number">Art. 58</td>
            <td class="article-content">
                <span class="article-title">Faltas muy graves</span><br>
                Son faltas muy graves las siguientes conductas:
                <ol class="alpha" type="a">
                    <li>Reincidir en dos (2) o m&aacute;s faltas graves durante el mismo ciclo acad&eacute;mico.</li>
                    <li>Agredir f&iacute;sica o verbalmente a cualquier miembro de la comunidad del CPU (autoridades, docentes, personal administrativo, estudiantes o terceros).</li>
                    <li>Realizar actos de violencia, amenaza, coacci&oacute;n o intimidaci&oacute;n contra cualquier persona dentro de las instalaciones del CPU o en actividades oficiales.</li>
                    <li>Cometer actos de fraude, suplantaci&oacute;n, copia il&iacute;cita, adulteraci&oacute;n de resultados o cualquier otra conducta deshonesta durante los ex&aacute;menes parciales, simulacros o cualquier evaluaci&oacute;n.</li>
                    <li>Introducir, poseer, consumir o comercializar bebidas alcoh&oacute;licas, drogas, sustancias psicotr&oacute;picas o estupefacientes dentro de las instalaciones del CPU o en actividades oficiales.</li>
                    <li>Portar armas u objetos peligrosos, aunque no se haga uso de ellos.</li>
                    <li>Causar da&ntilde;os intencionales y de consideraci&oacute;n a los bienes, instalaciones, equipos o materiales del CPU.</li>
                    <li>Realizar actos de discriminaci&oacute;n por raz&oacute;n de origen, raza, sexo, religi&oacute;n, opini&oacute;n, condici&oacute;n econ&oacute;mica o cualquier otra &iacute;ndole.</li>
                    <li>Realizar actos de connotaci&oacute;n sexual, hostigamiento sexual o cualquier conducta que atente contra la libertad, integridad o indemnidad sexual de cualquier persona.</li>
                    <li>Usar la imagen, nombre o identidad del CPU o de la UNPRG sin autorizaci&oacute;n para fines particulares o contrarios a los institucionales.</li>
                    <li>Suplantar la identidad de otro estudiante o persona en cualquier acto acad&eacute;mico o administrativo.</li>
                    <li>Promover, organizar o participar en organizaciones estudiantiles no autorizadas que pretendan atribuirse representaci&oacute;n o paralizar las actividades del CPU.</li>
                    <li>Incumplir las medidas cautelares o sanciones impuestas previamente.</li>
                </ol>
            </td>
        </tr>

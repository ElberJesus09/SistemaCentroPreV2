            <td class="article-content"><span class="article-title">Medidas cautelares</span><br>En caso de faltas muy graves, y para garantizar el normal desarrollo del procedimiento o la seguridad de la comunidad, el Coordinador General podr&aacute; disponer, de manera motivada, la suspensi&oacute;n preventiva del estudiante por un plazo m&aacute;ximo de quince (15) d&iacute;as calendario. La medida cautelar deber&aacute; ser notificada inmediatamente al estudiante y a sus padres o apoderados.</td>
        </tr>
    </table>


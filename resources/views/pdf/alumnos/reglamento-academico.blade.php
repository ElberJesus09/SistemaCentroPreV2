    <table class="article">
        <tr>
            <td class="article-number">Art. 59</td>
            <td class="article-content">
                <span class="article-title">Sanciones disciplinarias</span><br>
                Las sanciones que corresponden a las faltas disciplinarias, seg&uacute;n su gravedad, son:
                <ol class="alpha" type="a">
                    <li><span class="article-title">Amonestaci&oacute;n escrita:</span> para faltas leves. Consiste en una llamada de atenci&oacute;n por escrito, con copia al archivo personal del estudiante. La impone el Coordinador Acad&eacute;mico, previo informe del docente o autoridad que detect&oacute; la falta.</li>
                    <li><span class="article-title">Suspensi&oacute;n temporal:</span> para faltas graves. Consiste en la separaci&oacute;n del estudiante de todas las actividades acad&eacute;micas por un per&iacute;odo no menor de tres (3) ni mayor de diez (10) d&iacute;as calendarios. Durante la suspensi&oacute;n, el estudiante pierde el derecho a ser evaluado en las actividades que se realicen en dicho per&iacute;odo, obteniendo nota cero (00) en las mismas. La impone el Coordinador General, mediante resoluci&oacute;n motivada.</li>
                    <li><span class="article-title">Separaci&oacute;n definitiva:</span> para faltas muy graves. Implica la p&eacute;rdida inmediata de la condici&oacute;n de estudiante del CPU, la inhabilitaci&oacute;n para matricularse en ciclos posteriores y la p&eacute;rdida de todos los derechos derivados de la matr&iacute;cula, sin derecho a devoluci&oacute;n de pagos. La impone el Comit&eacute; Directivo, mediante resoluci&oacute;n motivada, previo informe del Coordinador General.</li>
                </ol>
            </td>
        </tr>
    </table>

    <table class="article">
        <tr>
            <td class="article-number">Art. 60</td>
            <td class="article-content">
                <span class="article-title">Procedimiento sancionador</span><br>
                El procedimiento para la imposici&oacute;n de sanciones se sujeta a las siguientes reglas m&iacute;nimas:
                <ol class="alpha" type="a">
                    <li><span class="article-title">Inicio:</span> El procedimiento se inicia de oficio por la autoridad competente o por denuncia escrita de cualquier miembro de la comunidad del CPU, debiendo contener los hechos, la identificaci&oacute;n del presunto infractor y los medios probatorios, de ser el caso.</li>
                    <li><span class="article-title">Instrucci&oacute;n y cargos:</span> El Coordinador Acad&eacute;mico realiza las investigaciones preliminares. Si existen indicios razonables de falta, formula un escrito de cargos y notifica al estudiante, otorg&aacute;ndole un plazo no menor de tres (3) d&iacute;as h&aacute;biles para presentar sus descargos y ofrecer pruebas.</li>
                    <li><span class="article-title">Actuaci&oacute;n de pruebas:</span> La autoridad instructora (Coordinador Acad&eacute;mico) actuar&aacute; las pruebas ofrecidas y las que considere necesarias, dentro de un plazo no mayor de cinco (5) d&iacute;as h&aacute;biles.</li>
                    <li><span class="article-title">Resoluci&oacute;n:</span> Concluida la instrucci&oacute;n, la autoridad competente (seg&uacute;n el art&iacute;culo 59: Sanciones disciplinarias) emitir&aacute; resoluci&oacute;n debidamente motivada en un plazo no mayor de cinco (5) d&iacute;as h&aacute;biles, declarando la imposici&oacute;n de la sanci&oacute;n o el archivo del procedimiento.</li>
                    <li><span class="article-title">Recursos:</span> Contra la resoluci&oacute;n que impone una sanci&oacute;n, el estudiante puede interponer recurso de reconsideraci&oacute;n ante la misma autoridad dentro del plazo de tres (3) d&iacute;as h&aacute;biles, o recurso de apelaci&oacute;n ante el Comit&eacute; Directivo, dentro del mismo plazo. La interposici&oacute;n del recurso no suspende la ejecuci&oacute;n de la sanci&oacute;n, salvo que la autoridad disponga lo contrario de manera motivada.</li>
                    <li><span class="article-title">Registro y comunicaci&oacute;n:</span> Toda sanci&oacute;n impuesta deber&aacute; ser registrada y comunicada a los padres o apoderados, en el caso de estudiantes menores de edad.</li>
                </ol>
            </td>
        </tr>
    </table>

    <table class="article">
